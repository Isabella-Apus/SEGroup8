CREATE TABLE IF NOT EXISTS risk_audits (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, product_id BIGINT NOT NULL, snapshot_name VARCHAR(120) NOT NULL,
 snapshot_description TEXT NOT NULL, risk_level VARCHAR(16) NOT NULL, rule_hits VARCHAR(500) NOT NULL DEFAULT '',
 status VARCHAR(20) NOT NULL, decision_reason VARCHAR(500) NOT NULL DEFAULT '', admin_id BIGINT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS integration_outbox (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,event_type VARCHAR(80) NOT NULL,aggregate_id BIGINT NOT NULL,
 payload TEXT NOT NULL,status VARCHAR(20) NOT NULL,created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
